                <h3>Geometry and Curved Screens</h3>

                <p>It's not just about style. By gently bending the display, every pixel will tilt a little bit towards the audience. This effectively increases the sweet spot of the display without having to change the LEDs.</p>

                <ul>
                    <li>Curves widen the view.</li>
